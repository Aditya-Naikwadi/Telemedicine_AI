export function getSpecialtyById(id: string): MedicalSpecialty | undefined {
    return MEDICAL_SPECIALTIES.find((s) => s.id === id);
}

export function getSpecialtiesByKeyword(keyword: string): MedicalSpecialty[] {
    const lowerKeyword = keyword.toLowerCase();
    return MEDICAL_SPECIALTIES.filter(
        (s) =>
            s.keywords.some((k) => k.toLowerCase().includes(lowerKeyword)) ||
            s.name.toLowerCase().includes(lowerKeyword) ||
            s.associatedSymptoms.some((sym) =>
                sym.toLowerCase().includes(lowerKeyword)
            )
    );
}
